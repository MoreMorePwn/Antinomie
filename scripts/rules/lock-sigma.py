"""Write the hash-locked pip requirements of the managed Sigma tool.

Every package is pinned, and each pin lists the SHA-256 of every wheel that
the supported hosts can install: pure-Python wheels and CPython 3.11 to 3.14
manylinux x86-64 wheels. pip then installs only those exact files.

usage: lock-sigma.py OUTPUT
"""
import json
import re
import sys
import urllib.request

PINS = [
    ("pySigma", "2.0.1"),
    ("pySigma-backend-sqlite", "2.1.0"),
    ("certifi", "2026.7.22"),
    ("charset-normalizer", "3.5.2"),
    ("diskcache", "5.6.3"),
    ("diskcache-stubs", "5.6.3.6.20240818"),
    ("google-re2", "1.1.20251105"),
    ("idna", "3.20"),
    ("Jinja2", "3.1.6"),
    ("jq", "1.12.0"),
    ("MarkupSafe", "3.0.4"),
    ("packaging", "26.3"),
    ("pyparsing", "3.3.3"),
    ("PyYAML", "6.0.3"),
    ("requests", "2.34.2"),
    ("types-PyYAML", "6.0.12.20260906"),
    ("typing_extensions", "4.16.0"),
    ("urllib3", "2.8.0"),
]
PYTHONS = ("cp311", "cp312", "cp313", "cp314")


def usable(filename):
    """A wheel the supported hosts can install."""
    match = re.fullmatch(r".+-([^-]+)-([^-]+)-([^-]+)\.whl", filename)
    if not match:
        return False
    python, abi, platform = match.groups()
    if platform == "any":
        return abi == "none" and any(tag in ("py3", "py2") for tag in python.split("."))
    if not any(tag.startswith("manylinux") and tag.endswith("x86_64") for tag in platform.split(".")):
        return False
    tags = python.split(".")
    if abi == "abi3":
        # A stable-ABI wheel runs on its own and every later CPython 3.
        return any(re.fullmatch(r"cp3(\d+)", tag) and int(tag[3:]) <= 14 for tag in tags)
    return any(tag in PYTHONS for tag in tags)


def main():
    lines = [
        "# Generated by scripts/rules/lock-sigma.py; do not edit.",
        "# Installed with --require-hashes --only-binary=:all: --no-deps.",
    ]
    for name, version in PINS:
        with urllib.request.urlopen(f"https://pypi.org/pypi/{name}/{version}/json", timeout=30) as reply:
            release = json.load(reply)
        hashes = sorted(
            entry["digests"]["sha256"]
            for entry in release["urls"]
            if entry["packagetype"] == "bdist_wheel" and usable(entry["filename"]) and not entry.get("yanked")
        )
        if not hashes:
            sys.exit(f"{name} {version} has no usable wheel")
        lines.append(f"{name}=={version} \\")
        lines.extend(f"    --hash=sha256:{digest} \\" for digest in hashes[:-1])
        lines.append(f"    --hash=sha256:{hashes[-1]}")
    with open(sys.argv[1], "w") as output:
        output.write("\n".join(lines) + "\n")


if __name__ == "__main__":
    main()
