# build-feature-sample.sh — build the benign feature sample.
#
#   usage: tests/monitor/build-feature-sample.sh OUTPUT_DIR [--static]
#
# Writes OUTPUT_DIR/antinomie-feature-sample. The default build links glibc
# dynamically and keeps symbols, so capa and the Symbols tab see its imports;
# it refuses to finish when a symbol needs a newer glibc than the Debian
# trixie guest has (2.41). --static links statically instead.
set -euo pipefail
here=$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)
output=${1:?usage: build-feature-sample.sh OUTPUT_DIR [--static]}
mode=${2:-}
mkdir -p "$output"

# Embedded payloads, generated reproducibly: binwalk finds them in the
# executable, and the noise block raises the entropy of one region.
python3 -I - "$output/feature-sample-payloads.h" <<'EOF'
import gzip, io, struct, sys, zipfile, zlib

def array(name, data):
    rows = [", ".join(f"0x{b:02x}" for b in data[i:i + 16]) for i in range(0, len(data), 16)]
    return f"static const unsigned char {name}[{len(data)}] = {{\n    " + ",\n    ".join(rows) + "\n};\n"

text = b"Antinomie feature sample: embedded gzip payload.\n" * 40
buffer = io.BytesIO()
with gzip.GzipFile(filename="readme.txt", mode="wb", fileobj=buffer, mtime=0) as stream:
    stream.write(text)
payload_gzip = buffer.getvalue()

def chunk(kind, body):
    return struct.pack(">I", len(body)) + kind + body + struct.pack(">I", zlib.crc32(kind + body))
rows = b"".join(b"\x00" + b"".join(bytes((x * 8, y * 8, (x + y) * 4, 255)) for x in range(32))
                for y in range(32))
payload_png = (b"\x89PNG\r\n\x1a\n" + chunk(b"IHDR", struct.pack(">IIBBBBB", 32, 32, 8, 6, 0, 0, 0))
               + chunk(b"IDAT", zlib.compress(rows, 9)) + chunk(b"IEND", b""))

buffer = io.BytesIO()
with zipfile.ZipFile(buffer, "w", zipfile.ZIP_DEFLATED) as archive:
    info = zipfile.ZipInfo("notes/antinomie.txt", date_time=(2026, 1, 1, 0, 0, 0))
    archive.writestr(info, b"Antinomie feature sample: embedded zip member.\n" * 20)
payload_zip = buffer.getvalue()

state, noise = 0x2545F4914F6CDD1D, bytearray()
while len(noise) < 8192:
    state ^= (state << 13) & 0xFFFFFFFFFFFFFFFF
    state ^= state >> 7
    state ^= (state << 17) & 0xFFFFFFFFFFFFFFFF
    noise += state.to_bytes(8, "little")

with open(sys.argv[1], "w") as header:
    header.write("/* Generated by build-feature-sample.sh; do not edit. */\n")
    for name, data in [("payload_gzip", payload_gzip), ("payload_png", payload_png),
                       ("payload_zip", payload_zip), ("payload_noise", bytes(noise))]:
        header.write(array(name, data))
EOF

flags=(-std=gnu11 -O1 -fno-inline -Wall -Wextra -Wno-unused-result -fstack-protector-strong
       -D_FORTIFY_SOURCE=2 -I "$output")
if [[ $mode == --static ]]; then
    gcc "${flags[@]}" -static -o "$output/antinomie-feature-sample" "$here/feature-sample.c" -pthread
else
    gcc "${flags[@]}" -pie -fPIE -Wl,-z,relro,-z,now \
        -o "$output/antinomie-feature-sample" "$here/feature-sample.c" -pthread
    newest=$(objdump -T "$output/antinomie-feature-sample" | grep -o 'GLIBC_[0-9.]*' | sort -uV | tail -1)
    if [[ $(printf '%s\nGLIBC_2.41\n' "$newest" | sort -V | tail -1) != GLIBC_2.41 ]]; then
        echo "needs $newest, newer than the guest's glibc 2.41; rebuild with --static" >&2
        exit 1
    fi
fi
sha256sum "$output/antinomie-feature-sample"
